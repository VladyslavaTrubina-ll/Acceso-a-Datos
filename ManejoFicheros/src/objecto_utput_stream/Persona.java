package objecto_utput_stream;

import java.io.Serializable;

/**
 * Интерфейс Serializable (Сериализация) — это интерфейс-маркер.
 * В нем нет никаких методов, которые нужно было бы писать внутри класса.
 * 
 * ДЛЯ ЧЕГО НУЖЕН: 
 * Добавляя "implements Serializable", мы вешаем на класс "бирку", которая говорит Java: 
 * "Я разрешаю превращать объекты этого класса в поток байтов".
 * Без этой "бирки" Java из соображений безопасности выдаст ошибку NotSerializableException,
 * если ты попытаешься записать объект в файл.
 * 
 * КАК РАБОТАЕТ:
 * Когда специальный класс (ObjectOutputStream) попытается записать этот объект в файл,
 * Java автоматически возьмет все его поля (nif, nombre, edad), превратит их в байты
 * и "склеит" в единый кусок данных. Позже Java сможет прочитать эти байты и 
 * автоматически собрать из них точную копию объекта (это называется десериализацией).
 */
public class Persona implements Serializable {
    
    // Все эти данные (состояние объекта) будут автоматически сохранены в файл
    private String nif;
    private String nombre;
    private int edad;

    // Конструктор нужен, чтобы мы могли создать объект в памяти перед сохранением
    public Persona(String nif, String nombre, int edad) {
        this.nif = nif;
        this.nombre = nombre;
        this.edad = edad;
    }
    
    // Геттеры и сеттеры нужны для обычной работы программы (чтобы другие классы могли
    // узнать имя или возраст). На сам процесс сохранения (сериализации) они не влияют — 
    // Java сохраняет значения переменных (nif, nombre, edad) напрямую из памяти.
    public String getNombre() { return nombre; }
    public int getEdad() { return edad; }
}